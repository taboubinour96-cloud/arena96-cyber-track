"""
Professional Security Audit & Bug Bounty Report Builder (`ReportBuilder`).

Exports findings into three industry-standard formats:
1. Structured Markdown Assessment Report (ready for human auditor verification & remediation)
2. SARIF 2.1.0 JSON (compatible with GitHub Code Scanning & VS Code SARIF Viewer)
3. Canonical JSON dictionary for multi-agent orchestration
"""

from __future__ import annotations

import json
from typing import Any, Dict, List

from .models import AuditFinding, AuditSummaryReport, Severity, TriageStatus

_SEVERITY_ORDER = {
    Severity.CRITICAL: 0,
    Severity.HIGH: 1,
    Severity.MEDIUM: 2,
    Severity.LOW: 3,
    Severity.INFO: 4,
}

_SARIF_LEVEL_MAP = {
    Severity.CRITICAL: "error",
    Severity.HIGH: "error",
    Severity.MEDIUM: "warning",
    Severity.LOW: "note",
    Severity.INFO: "note",
}


class ReportBuilder:
    """Formats `AuditSummaryReport` into Markdown, SARIF 2.1.0, and JSON."""

    @staticmethod
    def sort_findings(findings: List[AuditFinding]) -> List[AuditFinding]:
        return sorted(
            findings,
            key=lambda f: (
                f.triage_status == TriageStatus.LIKELY_FALSE_POSITIVE,
                _SEVERITY_ORDER[f.severity],
                -f.cvss_score,
                f.location.file_path,
                f.location.line_start,
            ),
        )

    @classmethod
    def to_markdown(cls, report: AuditSummaryReport) -> str:
        counts = report.counts_by_severity()
        active = cls.sort_findings(report.active_findings())
        suppressed = [
            f for f in report.findings if f.triage_status == TriageStatus.LIKELY_FALSE_POSITIVE
        ]

        lines: List[str] = [
            f"# Security Code Audit Report — {report.program_name}",
            "",
            "> **Mandatory Human-in-the-Loop Verification Notice:** This report was generated by the "
            "White-Box Security Audit Branch via static AST, configuration, authorization, and supply-chain "
            "analysis. In accordance with professional bug bounty and disclosure policies (HackerOne / Bugcrowd / "
            "Open-Source Security Policies), **a human security engineer must manually review reachability, "
            "business context, and program scope** before filing any external disclosure.",
            "",
            "## 1. Executive Summary",
            "",
            f"- **Target Workspace:** `{report.target_directory}`",
            f"- **Scanned Source & Config Files:** `{report.scanned_files_count}`",
            f"- **Discovered HTTP Endpoints:** `{len(report.discovered_routes)}`",
            f"- **Active Security Candidates:** `{len(active)}` "
            f"(Filtered Likely False Positives: `{len(suppressed)}`)",
            "",
            "| Severity | Active Findings |",
            "| :--- | :---: |",
            f"| CRITICAL (9.0 - 10.0) | {counts['CRITICAL']} |",
            f"| HIGH (7.0 - 8.9) | {counts['HIGH']} |",
            f"| MEDIUM (4.0 - 6.9) | {counts['MEDIUM']} |",
            f"| LOW (0.1 - 3.9) | {counts['LOW']} |",
            f"| INFO (0.0) | {counts['INFO']} |",
            "",
        ]

        if report.discovered_routes:
            lines.extend(
                [
                    "## 2. HTTP Route & Authorization Coverage Map",
                    "",
                    "| Framework | Method | Route | Handler | File:Line | Auth Guard Detected |",
                    "| :--- | :---: | :--- | :--- | :--- | :---: |",
                ]
            )
            for ep in report.discovered_routes:
                guard_badge = "Yes" if ep.has_auth_guard else "**NO (Review)**"
                lines.append(
                    f"| {ep.framework} | `{ep.http_method}` | `{ep.route_path}` | "
                    f"`{ep.handler_name}` | `{ep.file_path}:{ep.line_number}` | {guard_badge} |"
                )
            lines.append("")

        lines.append("## 3. Detailed Security Findings & Defensive Remediations")
        lines.append("")

        if not active:
            lines.append("_No active security findings detected within the scanned scope._")
            lines.append("")
        else:
            for idx, f in enumerate(active, start=1):
                lines.extend(
                    [
                        f"### 3.{idx} [{f.severity.value}] {f.title} (`{f.finding_id}`)",
                        "",
                        f"- **Rule / Category:** `{f.rule_id}` ({f.category})",
                        f"- **Classification:** `{f.cwe_id}` | `{f.owasp_category}`",
                        f"- **CVSS v3.1 Base Score:** **{f.cvss_score}** (`{f.cvss_vector}`)",
                        f"- **Confidence / Triage:** `{f.confidence.value}` — `{f.triage_status.value}`",
                        f"- **Location:** `{f.location.file_path}` (Line {f.location.line_start}"
                        + (
                            f", Function `{f.location.function_name}`)"
                            if f.location.function_name
                            else ")"
                        ),
                        "",
                        "#### Code Trace",
                        "```text",
                        f.location.snippet,
                        "```",
                        "",
                        "#### Root Cause & Security Impact",
                        f"- **Root Cause:** {f.description}",
                        f"- **Theoretical Impact:** {f.impact_summary}",
                        "",
                        "#### Recommended Defensive Remediation",
                        f"{f.remediation}",
                        "",
                    ]
                )
                if f.secure_code_example:
                    lines.extend(
                        [
                            "```python",
                            f.secure_code_example,
                            "```",
                            "",
                        ]
                    )
                if f.triage_notes:
                    lines.append("**Triage Notes:**")
                    for note in f.triage_notes:
                        lines.append(f"- {note}")
                    lines.append("")
                lines.append("---")
                lines.append("")

        if suppressed:
            lines.extend(
                [
                    "## 4. Suppressed Likely False Positives (Filtered Noise)",
                    "",
                    "| ID | Rule | Location | Suppression Reason |",
                    "| :--- | :--- | :--- | :--- |",
                ]
            )
            for s in suppressed:
                reason = "; ".join(s.triage_notes) if s.triage_notes else "Filtered by triage"
                lines.append(
                    f"| `{s.finding_id}` | `{s.rule_id}` | `{s.location.file_path}:{s.location.line_start}` | {reason} |"
                )
            lines.append("")

        return "\n".join(lines)

    @classmethod
    def to_sarif(cls, report: AuditSummaryReport) -> Dict[str, Any]:
        """Produces an OASIS SARIF 2.1.0 compliant JSON object."""
        rules_map: Dict[str, Dict[str, Any]] = {}
        results: List[Dict[str, Any]] = []

        for f in cls.sort_findings(report.active_findings()):
            if f.rule_id not in rules_map:
                rules_map[f.rule_id] = {
                    "id": f.rule_id,
                    "name": f.title,
                    "shortDescription": {"text": f.title},
                    "fullDescription": {"text": f.description},
                    "help": {"text": f.remediation},
                    "properties": {
                        "tags": ["security", f.cwe_id, f.owasp_category],
                        "security-severity": str(f.cvss_score),
                    },
                }

            results.append(
                {
                    "ruleId": f.rule_id,
                    "level": _SARIF_LEVEL_MAP[f.severity],
                    "message": {
                        "text": f"{f.description} Remediation: {f.remediation}"
                    },
                    "locations": [
                        {
                            "physicalLocation": {
                                "artifactLocation": {"uri": f.location.file_path},
                                "region": {
                                    "startLine": max(1, f.location.line_start),
                                    "endLine": max(1, f.location.line_end),
                                },
                            }
                        }
                    ],
                    "properties": {
                        "finding_id": f.finding_id,
                        "cwe": f.cwe_id,
                        "owasp": f.owasp_category,
                        "cvss_score": f.cvss_score,
                        "cvss_vector": f.cvss_vector,
                        "confidence": f.confidence.value,
                        "triage_status": f.triage_status.value,
                    },
                }
            )

        return {
            "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
            "version": "2.1.0",
            "runs": [
                {
                    "tool": {
                        "driver": {
                            "name": "CyberSecAuditBranch",
                            "version": "1.0.0",
                            "informationUri": "https://owasp.org/www-project-top-ten/",
                            "rules": list(rules_map.values()),
                        }
                    },
                    "results": results,
                }
            ],
        }

    @classmethod
    def to_json_string(cls, report: AuditSummaryReport) -> str:
        return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)
